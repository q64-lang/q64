// Build the edit-menu items for a field: Cut/Copy only with a selection; Paste
// always; Select All when there's text not already fully selected.
function buildEditItems(node) {
  const el = fieldEl(node);
  const value = renderCtx.textValue(node);
  const hasSel = el && el.selectionStart !== el.selectionEnd;
  const allSel = el && el.selectionStart === 0 && el.selectionEnd === value.length;
  const items = [];
  if (hasSel) {
    items.push({ id: EDIT.cut, glyph: glyphForStr('Cut') });
    items.push({ id: EDIT.copy, glyph: glyphForStr('Copy') });
  }
  items.push({ id: EDIT.paste, glyph: glyphForStr('Paste') });
  if (value && !allSel) items.push({ id: EDIT.selectAll, glyph: glyphForStr('Select All') });
  return items;
}

// Open the edit menu anchored at (px, py) — the touch point, so it lands on the
// field (above the keyboard) regardless of where the field scrolled.
function openEditMenu(node, px, py) {
  const items = buildEditItems(node);
  if (!items.length) return;
  editNode = node;
  editMenu = { anchor: { x: px, y: py, w: 0, h: 0 }, items, width: 150 };
  render();
}

// Replace the field's current selection with `repl` via the hidden element, then
// sync the host value + notify the handler (an `input` event).
function replaceSelection(node, repl) {
  const el = fieldEl(node);
  if (!el) return;
  const s = Math.min(el.selectionStart ?? 0, el.selectionEnd ?? 0);
  const e = Math.max(el.selectionStart ?? 0, el.selectionEnd ?? 0);
  try { el.setRangeText(repl, s, e, 'end'); } catch { el.value = el.value.slice(0, s) + repl + el.value.slice(e); }
  (node._text ??= {})[TEXTKEY.value] = el.value;
  dispatchText(node, EVENT.input, el.value);
}

// Select the whitespace-delimited word around index `idx` in the field. Returns
// true if a non-empty word was selected. Used by long-press (the reliable
// select gesture, since a drag fights the keyboard-open lift).
function selectWordAt(node, idx) {
  const el = fieldEl(node);
  if (!el) return null;
  const v = el.value;
  if (!v) return null;
  let s = Math.min(idx, v.length), e = s;
  const word = (c) => c && /\S/.test(c);
  while (s > 0 && word(v[s - 1])) s--;
  while (e < v.length && word(v[e])) e++;
  if (e > s) { try { el.setSelectionRange(s, e); } catch {} return { start: s, end: e }; }
  return null;
}

// Perform the chosen edit action (clipboard is async + gesture-gated).
async function doEdit(id) {
  const node = editNode;
  editMenu = null; editNode = null;
  if (!node) { render(); return; }
  const el = fieldEl(node);
  if (el) {
    const s = Math.min(el.selectionStart, el.selectionEnd), e = Math.max(el.selectionStart, el.selectionEnd);
    if (id === EDIT.cut || id === EDIT.copy) {
      try { await navigator.clipboard.writeText(el.value.slice(s, e)); } catch {}
      if (id === EDIT.cut) replaceSelection(node, '');
    } else if (id === EDIT.paste) {
      let t = ''; try { t = await navigator.clipboard.readText(); } catch {}
      if (t) replaceSelection(node, t);
    } else if (id === EDIT.selectAll) {
      try { el.setSelectionRange(0, el.value.length); } catch {}
    }
  }
  render();
}

// The menu spec for the currently-open node (or null) — built fresh each use so
// it reflects current selection/geometry. The host injects the viewport (CSS px)
// so the popup can flip/clamp to stay on-screen.
function openMenuSpec() {
  if (openDropdownId === null) return null;
  const n = nodes.get(openDropdownId);
  const w = n && widgetFor(n.kind);
  if (!w || !w.menuSpec) return null;
  return withViewport(w.menuSpec(n, renderCtx));
}

// Inject the viewport (CSS px) into a popup spec so it can flip/clamp on-screen.
function withViewport(spec) {
  if (spec) {
    const cv = document.getElementById('gpu');
    if (cv) spec.viewport = { w: cv.clientWidth, h: cv.clientHeight };
  }
  return spec;
}

// A glyph for a host-catalog id directly (popup option rows), cached.
const idGlyphCache = new Map();
function glyphForCatalog(textId) {
  const n = Number(textId);
  const str = (n >= CATALOG_BASE && n - CATALOG_BASE < CATALOG.length) ? CATALOG[n - CATALOG_BASE] : String(n);
  if (!idGlyphCache.has(str)) idGlyphCache.set(str, sdfTexture(str));
  return idGlyphCache.get(str);
}

// An SDF for an arbitrary string at a size, cached by "size:str". For text_input
// values, which change per keystroke and have no per-node glyph slot. Empty
// string → null (nothing to draw). Cache is unbounded but a UI types few strings.
const strGlyphCache = new Map();
function glyphForStr(str, sizePx = 17) {
  if (!str) return null;
  const key = `${sizePx}:${str}`;
  if (!strGlyphCache.has(key)) strGlyphCache.set(key, sdfTexture(str, sizePx));
  return strGlyphCache.get(key);
}

// An icon's SDF texture, cached by "iconId:size". Returns null for an unknown
// id. Drawn as a tinted quad (like a glyph); resolution-independent.
const iconGlyphCache = new Map();
function iconGlyph(iconId, sizePx = 22) {
  const n = Number(iconId);
  if (!(n >= 0 && n < ICONS.length)) return null;
  const key = `${n}:${sizePx}`;
  if (!iconGlyphCache.has(key)) iconGlyphCache.set(key, iconSdf(ICONS[n], sizePx));
  return iconGlyphCache.get(key);
}

// ===========================================================================
// Phase 1 — LAYOUT (one pure pass, SwiftUI-style). Geometry only: measure +
// arrange the tree into resolved rects (layoutMap). No scroll, no GPU, no clip.
// Recomputed only when the tree changes (layout()), NOT every frame. Also derives
// the content height and the sticky-header band from the pure geometry.
// ===========================================================================
let headerH = 0;            // bottom of the pinned header band (layout space)
function layout() {
  layoutMap = computeLayout(scene, layoutCtx);
  contentH = 0; headerH = 0; contentW = 0;
  for (const [id, rc] of layoutMap) {
    contentH = Math.max(contentH, rc.y + rc.h);
    contentW = Math.max(contentW, rc.x + rc.w);
    const n = nodes.get(id);
    if (n && n._pinned) headerH = Math.max(headerH, rc.y + rc.h);
  }
}

// ===========================================================================
// Phase 2 — RENDER PATH (consumes the resolved geometry). Applies scroll as a
// draw-time translate, clips scrollable content below the sticky header, draws.
// The GPU host and the soft renderer are two such paths over the same layout.
// ===========================================================================
function render() {
  // Frame timestamp for time-based animation (spinner). FROZEN while a field is
  // focused so the spinner holds — the caret-blink/keystroke renders that still
  // run during text entry won't keep stepping it forward.
  if (focusedId === null) renderCtx.now = performance.now();
  const cv = document.getElementById('gpu');
  viewportH = cv ? cv.clientHeight : 0;
  const viewportW = cv ? cv.clientWidth : 0;
  // Center the content block when the viewport is wider than it (iPad/desktop);
  // the layout was built left-anchored (x from 0), so this shifts the whole UI.
  offsetX = Math.max(0, Math.round((viewportW - contentW) / 2));
  // NB: scrollY is NOT hard-clamped here — it may sit slightly past the edges
  // during an iOS-style rubber-band overscroll; the drag applies resistance and
  // release springs it back (see settleScroll). maxBound() is the true limit.

  const frame = beginFrame(THEME.bg);
  renderCtx.pass = frame.pass;
  // Pass 1: scrollable (unpinned) content, clipped below the header band.
  if (headerH > 0) setScissor(frame.pass, { x: 0, y: headerH, w: 10000, h: Math.max(0, viewportH - headerH) });
  walk(ROOT, false);
  // Pass 2: pinned chrome (the sticky header), unclipped, on top.
  setScissor(frame.pass, null);
  if (headerH > 0) walk(ROOT, true);
  // Overlays last, on top of everything: the open menu or context menu (shared
  // popup primitive). Both get the viewport so they flip/clamp near edges.
  const spec = contextSpec ? withViewport(contextSpec) : openMenuSpec();
  if (spec) drawMenu(spec, renderCtx);
  if (editMenu) drawMenu(withViewport(editMenu), renderCtx);  // text-field edit menu, on top
  endFrame(frame);
}
// walk with a `pinned` filter: false = draw only unpinned subtrees; true = only
// pinned nodes. A node's pinned-ness is inherited from its nearest pinned ancestor.
function walk(id, wantPinned, pinned = false) {
  const n = nodes.get(id); if (!n) return;
  const isPinned = pinned || !!n._pinned;
  if (id !== ROOT && isPinned === wantPinned) {
    const w = widgetFor(n.kind);
    if (w && w.draw) w.draw(n, renderCtx);
  }
  for (const c of n.children) walk(c, wantPinned, isPinned);
}

// ---- input: hit-test the tree, fire the wired handler via on_event -----------
function hitTest(px, py) {
  // Topmost-first: later children draw over earlier; walk in reverse.
  let found = null;
  const visit = (id) => {
    const n = nodes.get(id); if (!n) return;
    for (let i = n.children.length - 1; i >= 0; i--) visit(n.children[i]);
    if (found) return;
    if (id !== ROOT) {
      const w = widgetFor(n.kind);
      if (w && w.hit && w.hit(n, px, py, renderCtx)) found = n;
    }
  };
  visit(ROOT);
  return found;
}

function dispatch(node, event, payload = 0) {
  // Find the handler for this event; if the node has no handler for this exact
  // event (e.g. a slider wired to `press` but we're sending `input` during a
  // drag), fall back to its single registered handler. A Stage-1 control wires
  // exactly one handler, so this routes drag/input to it without the producer
  // having to wire every event id.
  let handler = node.handlers.get(event);
  if (handler === undefined) {
    if (node.handlers.size === 1) handler = node.handlers.values().next().value;
    else return;
  }
  // Stage-1 dispatch (spec/qview-protocol.md §Events). The wasm handler reads
  // state, mutates the exact node(s), and calls present(). Two shapes, in order:
  //   1. per-handler export `on_<id>` (the handler id from qview.on) — branchless,
  //      one export per wired control; what the compiler emits cleanly today.
  //   2. single dispatcher `on_event(node, event)` — fallback when no on_<id>.
  // All take (node, event, payload) i64 args: `payload` is a widget-computed
  // value (e.g. a slider's value from the touch position) — the event-payload
  // shape from the spec. Handlers that ignore it just take fewer params.
  const perHandler = instance.exports[`on_${handler}`];
  const fn = typeof perHandler === 'function' ? perHandler : instance.exports.on_event;
  if (typeof fn === 'function') fn(BigInt(node.id), BigInt(event), BigInt(Math.trunc(payload)));
  else log(`wasm exports no on_${handler} or on_event`);
}

// Dispatch a text event to a node's handler, passing the string as a `str` param:
// write the UTF-8 into the wasm text buffer and call on_<id>(node, event, ptr,
// len). The handler reads/validates it (text.len, ==, slice, …) and mutates the
// tree + present()s. Only the per-handler `on_<id>` shape carries a str param.
function dispatchText(node, event, str) {
  let handler = node.handlers.get(event);
  if (handler === undefined) {
    if (node.handlers.size === 1) handler = node.handlers.values().next().value;
    else return;
  }
  const fn = instance.exports[`on_${handler}`];
  if (typeof fn !== 'function') return;
  const bytes = new TextEncoder().encode(str);
  const n = Math.min(bytes.length, TEXT_CAP);
  new Uint8Array(instance.exports.memory.buffer, TEXT_BUF, TEXT_CAP).set(bytes.subarray(0, n));
  // node/event are i64 (BigInt); ptr/len are i32 address-width params (Number).
  fn(BigInt(node.id), BigInt(event), TEXT_BUF, n);
}

// Give a text field keyboard focus: position the hidden <input> over it (so iOS
// keeps it on-screen + scrolls to it), seed its value, and focus() — which must
// run inside the tap gesture to raise the soft keyboard. We draw the text/caret;
// the input only captures keystrokes.
// Start/refresh the caret blink (visible now, then toggle ~every 530ms). Called
// on focus and reset on each keystroke so the caret stays solid while typing.
function startBlink() {
  caretOn = true;
  if (blinkTimer) clearInterval(blinkTimer);
  blinkTimer = setInterval(() => { caretOn = !caretOn; if (focusedId !== null) render(); }, 530);
}
function stopBlink() { if (blinkTimer) clearInterval(blinkTimer); blinkTimer = null; caretOn = true; }

// Lift the focused field above the keyboard exactly ONCE per focus session.
// iOS fires extra visualViewport resizes (e.g. the predictive bar appears on the
// first keystroke) that would otherwise re-scroll and make the field jump again;
// the latch keeps the lift to the single keyboard-open event.
function liftFocusedOnce() {
  if (focusedId === null || kbScrolled) return;
  kbInset = viewportInset();
  if (kbInset <= 0) return;                      // keyboard not up yet — wait for the resize
  ensureFocusedVisible();
  kbScrolled = true;
}

// A text field (single-line input or multi-line area)?
function isTextField(kind) { return kind === KIND.text_input || kind === KIND.text_area; }
// The hidden capture element for a node: a <textarea> (newlines) for text_area,
// else the single-line <input>. Both pinned top-left, invisible.
function fieldEl(node) { return document.getElementById(node && node.kind === KIND.text_area ? 'kbdm' : 'kbd'); }

function focusField(node, px, py) {
  const el = fieldEl(node);
  const w = widgetFor(node.kind);
  // Map the tap to a caret index (tap-to-position); fall back to end-of-text.
  const idx = (w && w.caretAt && px != null) ? w.caretAt(node, px, py, renderCtx) : renderCtx.textValue(node).length;
  // Already focused → just move the caret (no re-focus, no keyboard flicker).
  if (focusedId === node.id) {
    if (el) { try { el.setSelectionRange(idx, idx); } catch {} }
    startBlink();
    render();
    return;
  }
  focusedId = node.id;
  kbScrolled = false;
  if (spinRAF) { cancelAnimationFrame(spinRAF); spinRAF = 0; }  // stop animation now (don't wait a frame)
  startBlink();
  // The capture element is pinned top-left (always visible) so iOS never
  // auto-scrolls to it — we lift the drawn field ourselves. Seed its value +
  // focus (focus() must run inside the tap gesture to raise the soft keyboard)
  // and place the caret where the user tapped.
  if (el) {
    el.value = renderCtx.textValue(node);
    el.focus();
    try { el.setSelectionRange(idx, idx); } catch {}
  }
  render();
  // The keyboard animates in over a few hundred ms; the visualViewport 'resize'
  // (keyboard appearing) lifts the field and latches it. This timeout is a
  // fallback if that event doesn't fire; both go through liftFocusedOnce so the
  // field is lifted exactly once (no second jump on the first keystroke).
  setTimeout(liftFocusedOnce, 350);
}

// Drop keyboard focus and commit (a `change` event to the handler).
function blurField() {
  if (focusedId === null) return;
  const node = nodes.get(focusedId);
  focusedId = null;
  kbScrolled = false;
  stopBlink();
  kbInset = 0;                                   // keyboard closing; restore the normal bound
  const el = fieldEl(node);
  if (el) el.blur();
  // Do NOT snap scrollY back to the new (smaller) bound — that yanks the view
  // down when the keyboard dismisses. Leave it where it is; if it's now past the
  // end, the next scroll rubber-bands it back smoothly (settleScroll/momentum).
  if (node) dispatchText(node, EVENT.change, renderCtx.textValue(node));
  render();
  ensureSpin();                                  // resume the animation loop (paused while focused)
}

// ---- Snap: the device captures its OWN WebGPU canvas + uploads it ------------
// This is the scaling story: rendering + capture happen on the customer's device
// (their GPU), the server only stores bytes. We render a fresh frame, grab the
// canvas as a PNG blob, and POST it to the api's /api/snap with the deploy's
// snap:create token; the api stores it in R2 and returns a public URL.
let lastSnapUrl = '';
function wireSnapButton() {
  const btn = document.getElementById('snap');
  const copyBtn = document.getElementById('copy');
  if (!btn) return;
  if (!SNAP.api || !SNAP.token) { btn.disabled = true; btn.title = 'snap not configured'; if (copyBtn) copyBtn.disabled = true; return; }
  btn.addEventListener('click', async () => {
    btn.disabled = true; const label = btn.textContent; btn.textContent = '…';
    try {
      const url = await captureAndUpload();
      lastSnapUrl = url;
      // Auto-copy the URL to the clipboard so it's ready to paste immediately
      // (the click is a user gesture, so clipboard write is permitted).
      let copied = false;
      try { if (navigator.clipboard?.writeText) { await navigator.clipboard.writeText(url); copied = true; } } catch {}
      btn.textContent = '✓';
      if (copyBtn) copyBtn.disabled = false;
      const el = document.getElementById('log');
      if (el) { el.textContent = copied ? 'snap (copied): ' : 'snap: '; const a = document.createElement('a');
        a.href = url; a.textContent = url; a.target = '_blank'; a.style.color = '#5fd4ff'; el.appendChild(a); }
    } catch (e) {
      btn.textContent = '✗'; log('snap failed: ' + (e?.message || e));
    } finally {
      setTimeout(() => { btn.textContent = label; btn.disabled = false; }, 1500);
    }
  });
  // Copy: put the last snap URL on the clipboard (fast paste). Falls back to a
  // hidden textarea+execCommand if the async clipboard API is unavailable.
  if (copyBtn) copyBtn.addEventListener('click', async () => {
    if (!lastSnapUrl) return;
    const label = copyBtn.textContent;
    try {
      if (navigator.clipboard?.writeText) await navigator.clipboard.writeText(lastSnapUrl);
      else {
        const ta = document.createElement('textarea'); ta.value = lastSnapUrl;
        ta.style.position = 'fixed'; ta.style.opacity = '0'; document.body.appendChild(ta);
        ta.focus(); ta.select(); document.execCommand('copy'); ta.remove();
      }
      copyBtn.textContent = '✓';
    } catch { copyBtn.textContent = '✗'; }
    setTimeout(() => { copyBtn.textContent = label; }, 1200);
  });
}

async function captureAndUpload() {
  const canvas = document.getElementById('gpu');
  // Render a fresh frame so the WebGPU drawing buffer is populated. We must read
  // it back in the SAME turn (the buffer is cleared at the next present()).
  render();
  // Grab the canvas as a PNG blob. WebGPU canvas readback is finicky on Safari,
  // so try createImageBitmap -> 2D canvas -> blob first (forces a sync read of
  // the live buffer), then fall back to OffscreenCanvas.convertToBlob / toBlob.
  const blob = await canvasToPng(canvas);
  if (!blob) throw new Error('canvas capture returned empty (WebGPU readback failed)');
  const res = await fetch(`${SNAP.api}/api/snap`, {
    method: 'POST',
    headers: { 'authorization': `Bearer ${SNAP.token}`, 'content-type': 'image/png' },
    body: blob,
  });
  const j = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(j.error || `api ${res.status}`);
  return j.url;
}

async function canvasToPng(canvas) {
  // Path A: copy the live WebGPU buffer into a 2D canvas via an ImageBitmap.
  try {
    const bmp = await createImageBitmap(canvas);
    const off = new OffscreenCanvas(bmp.width, bmp.height);
    off.getContext('2d').drawImage(bmp, 0, 0);
    bmp.close?.();
    if (off.convertToBlob) return await off.convertToBlob({ type: 'image/png' });
  } catch {}
  // Path B: direct toBlob on the canvas (works once COPY_SRC is configured).
  return await new Promise((r) => canvas.toBlob(r, 'image/png'));
}

async function main() {
  // Stamp the build into the header title span (not the whole header — that holds
  // the Snap button too) so you can confirm you're on the latest deploy.
  // Lead the title with the short git sha so it stays visible even when the
  // header ellipsizes on a narrow iPhone (the long full stamp is cut from the
  // right). e.g. "build 5530203 · QView retained".
  const ttl = document.querySelector('header .ttl');
  if (ttl) {
    const sha = (BUILD.match(/\(([^)]+)\)/) || [, BUILD])[1];
    ttl.textContent = `build ${sha} · QView retained`;
    ttl.title = BUILD;   // full stamp on long-press / desktop hover
  }
  wireSnapButton();

  // Fully suppress the browser's default touch/gesture behaviour — the app owns
  // every gesture. Block iOS pinch-zoom (gesturestart), the page context menu,
  // and double-tap-zoom (a fast second tap). CSS handles scroll/callout/select.
  document.addEventListener('gesturestart', (e) => e.preventDefault());
  document.addEventListener('gesturechange', (e) => e.preventDefault());
  document.addEventListener('contextmenu', (e) => e.preventDefault());
  let lastTouchEnd = 0;
  document.addEventListener('touchend', (e) => {
    const now = Date.now();
    if (now - lastTouchEnd < 300) e.preventDefault();   // kill double-tap zoom
    lastTouchEnd = now;
  }, { passive: false });

  const canvas = document.getElementById('gpu');
  const resize = () => { canvas.width = Math.round(canvas.clientWidth * DPR); canvas.height = Math.round(canvas.clientHeight * DPR); };
  try { await initGPU(canvas); }
  catch (e) { log('WebGPU unavailable: ' + e.message + ' — open in a WebGPU-capable browser (iPad Safari 18+).'); return; }
  resize();

  const resp = await fetch('./screen.wasm');
  const bytes = await resp.arrayBuffer();
  const { instance: inst } = await WebAssembly.instantiate(bytes, ops());
  instance = inst;
  log(`retained host v${PROTOCOL_VERSION} · wasm32 (${bytes.byteLength} B) · WebGPU`);

  instance.exports._start();   // builds the retained tree + first present()

  // Pin the title bar (nodes 90/91) so it sticks at the top while content scrolls
  // beneath it. Scrollable content is CLIPPED to below the header (render() sets a
  // scissor), so scrolled text never bleeds over the sticky bar.
  for (const id of [90, 91]) { const n = nodes.get(id); if (n) n._pinned = true; }

  // A widget may expose value(node, px, py, r) -> i64 to turn a touch position
  // into a payload (e.g. a slider's value). If it does, the control is also
  // DRAGGABLE: we track the pointer and re-dispatch as it moves, so the thumb
  // follows the finger (EVENT.input during drag, EVENT.change implied on press).
  let dragNode = null, scrollDrag = null, textDrag = null;

  const localXY = (ev) => { const r = canvas.getBoundingClientRect(); return [ev.clientX - r.left, ev.clientY - r.top]; };

  // ---- scroll momentum (inertia) ----------------------------------------------
  // On release, the scroll keeps gliding at the finger's last velocity and decays
  // exponentially (iOS-like). A drag/wheel/tap cancels any running glide.
  let momentum = 0;            // px/frame velocity
  let momentumRAF = 0;
  const FRICTION = 0.94;       // per-frame decay (higher = longer glide)
  const MIN_V = 0.4;           // stop below this speed
  const RUBBER = 0.55;         // overscroll resistance (lower = stiffer past the edge)
  const SPRING = 0.22;         // spring-back stiffness toward the edge
  // maxBound() is module-scoped (keyboard-inset aware); see above.
  // How far past an edge scrollY currently is (signed: <0 past top, >0 past bottom).
  const overshoot = () => (scrollY < 0 ? scrollY : scrollY > maxBound() ? scrollY - maxBound() : 0);
  function stopMomentum() { if (momentumRAF) { cancelAnimationFrame(momentumRAF); momentumRAF = 0; } momentum = 0; }

  // One rAF loop that does both fling momentum AND spring-back, iOS-style: while
  // in-bounds it glides with friction; once past an edge it ignores momentum and
  // springs back to the boundary; when settled, stops.
  function startMomentum(v0) {
    stopMomentum();
    momentum = v0;
    const step = () => {
      const over = overshoot();
      if (over !== 0) {
        // Past an edge: spring toward it, kill fling velocity.
        momentum = 0;
        scrollY -= over * SPRING;
        if (Math.abs(over) < 0.5) { scrollY = scrollY < 0 ? 0 : maxBound(); render(); stopMomentum(); return; }
      } else {
        momentum *= FRICTION;
        scrollY += momentum;
        if (Math.abs(momentum) < MIN_V) { stopMomentum(); return; }
      }
      render();
      momentumRAF = requestAnimationFrame(step);
    };
    momentumRAF = requestAnimationFrame(step);
  }
  // Spring back to the nearest edge if currently overscrolled (used on release
  // when there's no fling). A no-op when in-bounds.
  function settleScroll() { if (overshoot() !== 0) startMomentum(0); }

  // Long-press (touch) / right-click (mouse) -> a context menu anchored at the
  // point, for any node whose widget exposes contextMenu(node, r). Reuses the
  // shared popup primitive (so it flips/clamps near edges too).
  const LONG_PRESS_MS = 500;
  const LONG_PRESS_SLOP = 10;   // px the finger may wobble during a hold
  let longPressTimer = null, longPressFired = false, longPressXY = null;
  const cancelLongPress = () => { if (longPressTimer) { clearTimeout(longPressTimer); longPressTimer = null; } longPressXY = null; };

  // Open a context menu for the node at (px,py), anchored at the point. Returns
  // true if a menu was raised.
  function openContextMenu(px, py) {
    const hit = hitTest(px, py);
    const w = hit && widgetFor(hit.kind);
    if (!w || !w.contextMenu) return false;
    const cm = w.contextMenu(hit, renderCtx);
    if (!cm || !cm.items || cm.items.length === 0) return false;
    contextSpec = { anchor: { x: px, y: py, w: 0, h: 0 }, items: cm.items, width: cm.width ?? 200 };
    contextNode = hit;
    render();
    return true;
  }

  canvas.addEventListener('pointerdown', (ev) => {
    stopMomentum();                              // a new touch halts any scroll glide
    const [px, py] = localXY(ev);

    // The edit menu captures the tap first: pick Cut/Copy/Paste/Select All, or
    // dismiss on an outside tap (the field keeps focus either way).
    if (editMenu) {
      ev.preventDefault();
      const chosen = hitMenu(withViewport(editMenu), px, py);
      if (chosen != null) doEdit(chosen);
      else { editMenu = null; editNode = null; render(); }
      return;
    }

    // If a menu is open, it captures this tap first (shared popup primitive):
    // pick an item (-> selection payload to the wasm) or dismiss on an outside tap.
    if (openDropdownId !== null || contextSpec) {
      const spec = contextSpec ? withViewport(contextSpec) : openMenuSpec();
      const target = contextSpec ? contextNode : nodes.get(openDropdownId);
      const chosen = hitMenu(spec, px, py);
      openDropdownId = null; contextSpec = null; contextNode = null;
      if (chosen !== null && chosen !== undefined && target) {
        dispatch(target, EVENT.change, chosen);     // wasm updates the field/selection
        // The platform dropdown re-themes the whole gallery live (iOS/Material/…).
        if (OPTION_PLATFORM[chosen]) setPlatform(OPTION_PLATFORM[chosen]);
      } else render();
      return;
    }

    const hit = hitTest(px, py);
    const w = hit && widgetFor(hit.kind);

    // Tapping a text field focuses it (summons the soft keyboard); tapping
    // anything else MAY dismiss it — but only on a real tap, decided at
    // pointerup (see endDrag). Do NOT blur here: a scroll gesture starts with a
    // pointerdown on empty space, and scrolling must keep the keyboard open.
    if (hit && isTextField(hit.kind)) {
      ev.preventDefault();
      const wt = widgetFor(hit.kind);
      // Focus + place the caret at the tap (the drag anchor); dragging extends
      // the selection from here.
      const anchor = wt && wt.caretAt ? wt.caretAt(hit, px, py, renderCtx) : 0;
      focusField(hit, px, py);
      textDrag = { node: hit, anchor, startX: px, startY: py };
      try { canvas.setPointerCapture(ev.pointerId); } catch {}
      // Long-press selects the WORD under the finger (the reliable select
      // gesture — a drag fights the keyboard-open lift). It does NOT open the
      // menu yet: while still holding, dragging adjusts the selection from the
      // word bounds; the menu appears on release (see endDrag). Empty word → the
      // release just shows the Paste / Select All menu.
      cancelLongPress();
      longPressXY = [px, py];
      longPressTimer = setTimeout(() => {
        longPressTimer = null;
        const idx = wt && wt.caretAt ? wt.caretAt(hit, px, py, renderCtx) : 0;
        const word = selectWordAt(hit, idx);
        if (textDrag && word) textDrag.word = word;  // enter adjust mode
        render();
      }, LONG_PRESS_MS);
      return;
    }

    // No interactive target under the finger -> arm a SCROLL drag (when content
    // overflows the viewport). A vertical drag on empty space / a label scrolls.
    if (!w || (!w.hit && !w.value && !w.menuSpec && !w.contextMenu)) {
      if (contentH + 16 > viewportH) {
        scrollDrag = { startY: py, startScroll: scrollY, moved: false };
        try { canvas.setPointerCapture(ev.pointerId); } catch {}
      }
      return;
    }

    // Arm long-press if this node has a context menu (touch raises it after a hold).
    if (w && w.contextMenu) {
      longPressFired = false;
      cancelLongPress();
      longPressXY = [px, py];
      longPressTimer = setTimeout(() => { longPressTimer = null; longPressFired = openContextMenu(px, py); }, LONG_PRESS_MS);
    }
    // A widget that can raise a menu (dropdown): toggle it open.
    if (w && w.menuSpec) {
      openDropdownId = hit.id;
      render();
      return;
    }
    if (w && typeof w.value === 'function') {
      // Ranged control: set value to where you touched (down = jump-to), and arm
      // dragging so the thumb tracks the finger. preventDefault + pointer capture
      // keep the whole drag ours (no scroll-steal when it drifts vertically).
      ev.preventDefault();
      dragNode = hit;
      try { canvas.setPointerCapture(ev.pointerId); } catch {}
      dispatch(hit, EVENT.input, w.value(hit, px, py, renderCtx));
      return;
    }
    // A context-menu-only node (no press handler) waits for the long-press; don't
    // flash a press for it.
    if (w && w.contextMenu && !(hit.handlers && hit.handlers.size)) return;
    pressedId = hit.id; render();                       // immediate pressed-state flash
    dispatch(hit, EVENT.press);                         // wasm mutates + presents
    setTimeout(() => { pressedId = null; render(); }, 120);
  }, { passive: false });

  canvas.addEventListener('pointermove', (ev) => {
    // Text selection drag: extend the field's selection from the anchor to the
    // character under the finger.
    if (textDrag) {
      ev.preventDefault();
      const [mx, my] = localXY(ev);
      // A real drag (beyond slop) cancels the pending long-press — it's a select.
      if (longPressTimer && Math.hypot(mx - textDrag.startX, my - textDrag.startY) > LONG_PRESS_SLOP) cancelLongPress();
      const wt = widgetFor(textDrag.node.kind);
      const idx = wt && wt.caretAt ? wt.caretAt(textDrag.node, mx, my, renderCtx) : textDrag.anchor;
      const el = fieldEl(textDrag.node);
      if (el) {
        let s, e;
        if (textDrag.word) {
          // Adjust mode (after a long-press word-select): the word stays
          // selected; drag past either end to grow the selection that way.
          const { start: ws, end: we } = textDrag.word;
          if (idx < ws) { s = idx; e = we; } else if (idx > we) { s = ws; e = idx; } else { s = ws; e = we; }
        } else {
          s = Math.min(textDrag.anchor, idx); e = Math.max(textDrag.anchor, idx);
        }
        try { el.setSelectionRange(s, e); } catch {}
      }
      render();
      return;
    }
    // Scroll drag: translate the scene by the finger's vertical delta, tracking
    // velocity (last-frame px delta) so release can launch momentum.
    if (scrollDrag) {
      ev.preventDefault();
      const [, py] = localXY(ev);
      const dy = py - scrollDrag.startY;
      if (Math.abs(dy) > 4) scrollDrag.moved = true;
      const prev = scrollY;
      let target = scrollDrag.startScroll - dy;          // drag down -> content moves down
      // iOS rubber-band: past an edge, the content follows the finger with
      // resistance (only RUBBER of the overscroll distance) instead of 1:1.
      const max = maxBound();
      if (target < 0) target = target * RUBBER;
      else if (target > max) target = max + (target - max) * RUBBER;
      scrollY = target;
      scrollDrag.vel = scrollY - prev;                   // px since last move = velocity
      render();
      return;
    }
    // Cancel a pending long-press only if the finger moves beyond the slop radius
    // (a real hold always wobbles a few px; a true drag/scroll exceeds slop).
    if (longPressTimer && longPressXY) {
      const [sx, sy] = longPressXY;
      const [mx, my] = localXY(ev);
      if (Math.hypot(mx - sx, my - sy) > LONG_PRESS_SLOP) cancelLongPress();
    }
    if (!dragNode) return;
    ev.preventDefault();
    // Only the x drives the value; vertical drift (e.g. toward a label) is
    // ignored, so the drag holds anywhere on the canvas once captured.
    const [px, py] = localXY(ev);
    const w = widgetFor(dragNode.kind);
    dispatch(dragNode, EVENT.input, w.value(dragNode, px, py, renderCtx));
  }, { passive: false });

  const endDrag = (ev) => {
    cancelLongPress();                          // a lift before the hold elapsed = a tap, not long-press
    if (textDrag) {
      cancelLongPress();
      try { canvas.releasePointerCapture(ev.pointerId); } catch {}
      const node = textDrag.node;
      textDrag = null;                          // selection already set during the move
      // A completed drag-select raises the edit menu at the finger (Cut/Copy).
      const el = fieldEl(node);
      if (el && el.selectionStart !== el.selectionEnd) {
        const [ux, uy] = localXY(ev);
        openEditMenu(node, ux, uy);
      }
      return;
    }
    if (scrollDrag) {
      try { canvas.releasePointerCapture(ev.pointerId); } catch {}
      const v = scrollDrag.vel || 0;
      const moved = scrollDrag.moved;
      scrollDrag = null;
      // A tap on empty space (no movement) dismisses the keyboard; a scroll
      // (moved) keeps it open. So tap-to-dismiss works, scrolling doesn't close.
      if (!moved && focusedId !== null) { blurField(); return; }
      // Flick -> glide (momentum also springs back if it hits an edge); otherwise
      // if we were left overscrolled, spring back to the boundary.
      if (Math.abs(v) > 1) startMomentum(v);
      else settleScroll();
      return;
    }
    if (!dragNode) return;
    try { canvas.releasePointerCapture(ev.pointerId); } catch {}
    dragNode = null;
  };
  canvas.addEventListener('pointerup', endDrag);
  canvas.addEventListener('pointercancel', endDrag);

  // Wheel / trackpad scroll (desktop) — clamps hard (no rubber-band for a wheel).
  canvas.addEventListener('wheel', (ev) => {
    if (maxBound() <= 0) return;
    ev.preventDefault();
    stopMomentum();
    scrollY = Math.max(0, Math.min(scrollY + ev.deltaY, maxBound()));
    render();
  }, { passive: false });

  // Right-click (desktop) -> the same context menu, anchored at the pointer.
  canvas.addEventListener('contextmenu', (ev) => {
    ev.preventDefault();                        // suppress the browser menu
    const [px, py] = localXY(ev);
    // Dismiss any open menu first; then raise the context menu (if any) here.
    openDropdownId = null; contextSpec = null; contextNode = null;
    if (!openContextMenu(px, py)) render();
  });

  // Hidden-element keystrokes drive the focused text field: the host owns the
  // value (so the field shows what's typed even if the handler ignores it), then
  // the handler gets an `input` event with the text. `blur` commits (`change`).
  // Both capture elements (#kbd input, #kbdm textarea) share the same handlers;
  // only one is focused at a time, and we read the event target's value.
  const onKbdInput = (e) => {
    if (focusedId === null) return;
    const node = nodes.get(focusedId);
    if (!node) return;
    (node._text ??= {})[TEXTKEY.value] = e.target.value;
    startBlink();                                // keep the caret solid while typing
    dispatchText(node, EVENT.input, e.target.value);
    render();
  };
  const onKbdBlur = () => { if (focusedId !== null) blurField(); };
  for (const id of ['kbd', 'kbdm']) {
    const el = document.getElementById(id);
    if (el) { el.addEventListener('input', onKbdInput); el.addEventListener('blur', onKbdBlur); }
  }
  // The soft keyboard shrinks the visual viewport. ONLY track the inset while a
  // field is focused — otherwise iPad's dynamic toolbar makes visualViewport.height
  // fluctuate during a normal scroll, which would oscillate kbInset -> maxBound()
  // and vibrate the rubber-band. After the one-time lift, kbInset is frozen so
  // maxBound() stays stable while scrolling with the keyboard up. No 'scroll'
  // listener (it fires continuously on iPad and isn't needed).
  if (window.visualViewport) {
    const onVV = () => {
      if (focusedId === null) { if (kbInset !== 0) { kbInset = 0; render(); } return; }
      if (!kbScrolled) {
        kbInset = viewportInset();
        if (kbInset > 0) liftFocusedOnce(); else render();
      }
    };
    window.visualViewport.addEventListener('resize', onVV);
  }

  // Re-fit on a viewport change: rebuild the backing store, refresh viewportH,
  // clamp scroll into the new range, redraw. GUARDED against no-op size changes:
  // resize() sets canvas.width/height (the drawing buffer), and a ResizeObserver
  // can re-fire from that — so if the CSS box is unchanged we bail, breaking the
  // feedback loop (the cause of the load-blank + scroll-vibration). During an
  // active scroll/momentum we don't clamp (so a mid-scroll toolbar resize can't
  // yank the position); we just track the size + redraw.
  let lastCW = -1, lastCH = -1;
  const refit = () => {
    // While a text field is focused, treat the keyboard as a pure overlay: do
    // NOT resize the canvas. On iPhone the keyboard/toolbar shrinks the layout
    // viewport, which fires the ResizeObserver during focus; resizing the canvas
    // backing store mid-keyboard dismisses the keyboard there. We handle keyboard
    // occlusion via the scroll-lift (kbInset), not a canvas resize.
    if (focusedId !== null) return;
    const cw = canvas.clientWidth, ch = canvas.clientHeight;
    if (cw === lastCW && ch === lastCH) return;   // no real change — don't loop
    lastCW = cw; lastCH = ch;
    resize();
    viewportH = ch;
    if (!scrollDrag && !momentumRAF) {
      stopMomentum();
      scrollY = Math.max(0, Math.min(scrollY, maxBound()));
    }
    render();
  };
  // A ResizeObserver on the canvas is the RELIABLE signal: iPad Safari does not
  // dependably fire window 'resize' for Stage Manager / split-view / multitasking
  // size changes, but the observer fires whenever the element's box actually
  // changes — so the canvas, scroll bounds, and centering always track the window.
  if (typeof ResizeObserver !== 'undefined') new ResizeObserver(refit).observe(canvas);
  // Keep the window listeners too (older Safari, desktop) — refit is idempotent.
  window.addEventListener('resize', refit);
  window.addEventListener('orientationchange', () => { refit(); requestAnimationFrame(refit); });

  // First-paint insurance: the initial present() can render before the canvas
  // has its final laid-out size on iPad (blank until a touch nudged a redraw).
  // Re-fit on the next frame, after load, and a beat later so the first frame is
  // drawn at the real size without needing a touch.
  requestAnimationFrame(refit);
  window.addEventListener('load', refit);
  setTimeout(refit, 120);
}
main();
