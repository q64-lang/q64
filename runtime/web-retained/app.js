let lastSnapUrl = '';
function wireSnapButton() {
  const btn = document.getElementById('snap');
  const copyBtn = document.getElementById('copy');
  if (!btn) return;
  if (!SNAP.api || !SNAP.token) { btn.disabled = true; btn.title = 'snap not configured'; if (copyBtn) copyBtn.disabled = true; return; }
  btn.addEventListener('click', async () => {
    btn.disabled = true; const label = btn.textContent; btn.textContent = '…';
    try {
      const url = await captureAndUpload();
      lastSnapUrl = url;
      // Auto-copy the URL to the clipboard so it's ready to paste immediately
      // (the click is a user gesture, so clipboard write is permitted).
      let copied = false;
      try { if (navigator.clipboard?.writeText) { await navigator.clipboard.writeText(url); copied = true; } } catch {}
      btn.textContent = '✓';
      if (copyBtn) copyBtn.disabled = false;
      const el = document.getElementById('log');
      if (el) { el.textContent = copied ? 'snap (copied): ' : 'snap: '; const a = document.createElement('a');
        a.href = url; a.textContent = url; a.target = '_blank'; a.style.color = '#5fd4ff'; el.appendChild(a); }
    } catch (e) {
      btn.textContent = '✗'; log('snap failed: ' + (e?.message || e));
    } finally {
      setTimeout(() => { btn.textContent = label; btn.disabled = false; }, 1500);
    }
  });
  // Copy: put the last snap URL on the clipboard (fast paste). Falls back to a
  // hidden textarea+execCommand if the async clipboard API is unavailable.
  if (copyBtn) copyBtn.addEventListener('click', async () => {
    if (!lastSnapUrl) return;
    const label = copyBtn.textContent;
    try {
      if (navigator.clipboard?.writeText) await navigator.clipboard.writeText(lastSnapUrl);
      else {
        const ta = document.createElement('textarea'); ta.value = lastSnapUrl;
        ta.style.position = 'fixed'; ta.style.opacity = '0'; document.body.appendChild(ta);
        ta.focus(); ta.select(); document.execCommand('copy'); ta.remove();
      }
      copyBtn.textContent = '✓';
    } catch { copyBtn.textContent = '✗'; }
    setTimeout(() => { copyBtn.textContent = label; }, 1200);
  });
}

async function captureAndUpload() {
  const canvas = document.getElementById('gpu');
  // Render a fresh frame so the WebGPU drawing buffer is populated. We must read
  // it back in the SAME turn (the buffer is cleared at the next present()).
  render();
  // Grab the canvas as a PNG blob. WebGPU canvas readback is finicky on Safari,
  // so try createImageBitmap -> 2D canvas -> blob first (forces a sync read of
  // the live buffer), then fall back to OffscreenCanvas.convertToBlob / toBlob.
  const blob = await canvasToPng(canvas);
  if (!blob) throw new Error('canvas capture returned empty (WebGPU readback failed)');
  const res = await fetch(`${SNAP.api}/api/snap`, {
    method: 'POST',
    headers: { 'authorization': `Bearer ${SNAP.token}`, 'content-type': 'image/png' },
    body: blob,
  });
  const j = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(j.error || `api ${res.status}`);
  return j.url;
}

async function canvasToPng(canvas) {
  // Path A: copy the live WebGPU buffer into a 2D canvas via an ImageBitmap.
  try {
    const bmp = await createImageBitmap(canvas);
    const off = new OffscreenCanvas(bmp.width, bmp.height);
    off.getContext('2d').drawImage(bmp, 0, 0);
    bmp.close?.();
    if (off.convertToBlob) return await off.convertToBlob({ type: 'image/png' });
  } catch {}
  // Path B: direct toBlob on the canvas (works once COPY_SRC is configured).
  return await new Promise((r) => canvas.toBlob(r, 'image/png'));
}

async function main() {
  // Stamp the build into the header title span (not the whole header — that holds
  // the Snap button too) so you can confirm you're on the latest deploy.
  const ttl = document.querySelector('header .ttl');
  if (ttl) ttl.textContent = `QView · retained · build ${BUILD}`;
  wireSnapButton();

  // Fully suppress the browser's default touch/gesture behaviour — the app owns
  // every gesture. Block iOS pinch-zoom (gesturestart), the page context menu,
  // and double-tap-zoom (a fast second tap). CSS handles scroll/callout/select.
  document.addEventListener('gesturestart', (e) => e.preventDefault());
  document.addEventListener('gesturechange', (e) => e.preventDefault());
  document.addEventListener('contextmenu', (e) => e.preventDefault());
  let lastTouchEnd = 0;
  document.addEventListener('touchend', (e) => {
    const now = Date.now();
    if (now - lastTouchEnd < 300) e.preventDefault();   // kill double-tap zoom
    lastTouchEnd = now;
  }, { passive: false });

  const canvas = document.getElementById('gpu');
  const resize = () => { canvas.width = Math.round(canvas.clientWidth * DPR); canvas.height = Math.round(canvas.clientHeight * DPR); };
  try { await initGPU(canvas); }
  catch (e) { log('WebGPU unavailable: ' + e.message + ' — open in a WebGPU-capable browser (iPad Safari 18+).'); return; }
  resize();

  const resp = await fetch('./screen.wasm');
  const bytes = await resp.arrayBuffer();
  const { instance: inst } = await WebAssembly.instantiate(bytes, ops());
  instance = inst;
  log(`retained host v${PROTOCOL_VERSION} · wasm32 (${bytes.byteLength} B) · WebGPU`);

  instance.exports._start();   // builds the retained tree + first present()

  // Pin the title bar (nodes 90/91) so it sticks at the top while content scrolls
  // beneath it. Scrollable content is CLIPPED to below the header (render() sets a
  // scissor), so scrolled text never bleeds over the sticky bar.
  for (const id of [90, 91]) { const n = nodes.get(id); if (n) n._pinned = true; }

  // A widget may expose value(node, px, py, r) -> i64 to turn a touch position
  // into a payload (e.g. a slider's value). If it does, the control is also
  // DRAGGABLE: we track the pointer and re-dispatch as it moves, so the thumb
  // follows the finger (EVENT.input during drag, EVENT.change implied on press).
  let dragNode = null, scrollDrag = null;

  const localXY = (ev) => { const r = canvas.getBoundingClientRect(); return [ev.clientX - r.left, ev.clientY - r.top]; };

  // ---- scroll momentum (inertia) ----------------------------------------------
  // On release, the scroll keeps gliding at the finger's last velocity and decays
  // exponentially (iOS-like). A drag/wheel/tap cancels any running glide.
  let momentum = 0;            // px/frame velocity
  let momentumRAF = 0;
  const FRICTION = 0.94;       // per-frame decay (higher = longer glide)
  const MIN_V = 0.4;           // stop below this speed
  const RUBBER = 0.55;         // overscroll resistance (lower = stiffer past the edge)
  const SPRING = 0.22;         // spring-back stiffness toward the edge
  // maxBound() is module-scoped (keyboard-inset aware); see above.
  // How far past an edge scrollY currently is (signed: <0 past top, >0 past bottom).
  const overshoot = () => (scrollY < 0 ? scrollY : scrollY > maxBound() ? scrollY - maxBound() : 0);
  function stopMomentum() { if (momentumRAF) { cancelAnimationFrame(momentumRAF); momentumRAF = 0; } momentum = 0; }

  // One rAF loop that does both fling momentum AND spring-back, iOS-style: while
  // in-bounds it glides with friction; once past an edge it ignores momentum and
  // springs back to the boundary; when settled, stops.
  function startMomentum(v0) {
    stopMomentum();
    momentum = v0;
    const step = () => {
      const over = overshoot();
      if (over !== 0) {
        // Past an edge: spring toward it, kill fling velocity.
        momentum = 0;
        scrollY -= over * SPRING;
        if (Math.abs(over) < 0.5) { scrollY = scrollY < 0 ? 0 : maxBound(); render(); stopMomentum(); return; }
      } else {
        momentum *= FRICTION;
        scrollY += momentum;
        if (Math.abs(momentum) < MIN_V) { stopMomentum(); return; }
      }
      render();
      momentumRAF = requestAnimationFrame(step);
    };
    momentumRAF = requestAnimationFrame(step);
  }
  // Spring back to the nearest edge if currently overscrolled (used on release
  // when there's no fling). A no-op when in-bounds.
  function settleScroll() { if (overshoot() !== 0) startMomentum(0); }

  // Long-press (touch) / right-click (mouse) -> a context menu anchored at the
  // point, for any node whose widget exposes contextMenu(node, r). Reuses the
  // shared popup primitive (so it flips/clamps near edges too).
  const LONG_PRESS_MS = 500;
  const LONG_PRESS_SLOP = 10;   // px the finger may wobble during a hold
  let longPressTimer = null, longPressFired = false, longPressXY = null;
  const cancelLongPress = () => { if (longPressTimer) { clearTimeout(longPressTimer); longPressTimer = null; } longPressXY = null; };

  // Open a context menu for the node at (px,py), anchored at the point. Returns
  // true if a menu was raised.
  function openContextMenu(px, py) {
    const hit = hitTest(px, py);
    const w = hit && widgetFor(hit.kind);
    if (!w || !w.contextMenu) return false;
    const cm = w.contextMenu(hit, renderCtx);
    if (!cm || !cm.items || cm.items.length === 0) return false;
    contextSpec = { anchor: { x: px, y: py, w: 0, h: 0 }, items: cm.items, width: cm.width ?? 200 };
    contextNode = hit;
    render();
    return true;
  }

  canvas.addEventListener('pointerdown', (ev) => {
    stopMomentum();                              // a new touch halts any scroll glide
    const [px, py] = localXY(ev);

    // If a menu is open, it captures this tap first (shared popup primitive):
    // pick an item (-> selection payload to the wasm) or dismiss on an outside tap.
    if (openDropdownId !== null || contextSpec) {
      const spec = contextSpec ? withViewport(contextSpec) : openMenuSpec();
      const target = contextSpec ? contextNode : nodes.get(openDropdownId);
      const chosen = hitMenu(spec, px, py);
      openDropdownId = null; contextSpec = null; contextNode = null;
      if (chosen !== null && chosen !== undefined && target) {
        dispatch(target, EVENT.change, chosen);     // wasm updates the field/selection
        // The platform dropdown re-themes the whole gallery live (iOS/Material/…).
        if (OPTION_PLATFORM[chosen]) setPlatform(OPTION_PLATFORM[chosen]);
      } else render();
      return;
    }

    const hit = hitTest(px, py);
    const w = hit && widgetFor(hit.kind);

    // Tapping a text field focuses it (summons the soft keyboard); tapping
    // anything else blurs the current field (dismisses it) before proceeding.
    if (hit && hit.kind === KIND.text_input) {
      ev.preventDefault();
      focusField(hit);
      return;
    }
    if (focusedId !== null) blurField();

    // No interactive target under the finger -> arm a SCROLL drag (when content
    // overflows the viewport). A vertical drag on empty space / a label scrolls.
    if (!w || (!w.hit && !w.value && !w.menuSpec && !w.contextMenu)) {
      if (contentH + 16 > viewportH) {
        scrollDrag = { startY: py, startScroll: scrollY, moved: false };
        try { canvas.setPointerCapture(ev.pointerId); } catch {}
      }
      return;
    }

    // Arm long-press if this node has a context menu (touch raises it after a hold).
    if (w && w.contextMenu) {
      longPressFired = false;
      cancelLongPress();
      longPressXY = [px, py];
      longPressTimer = setTimeout(() => { longPressTimer = null; longPressFired = openContextMenu(px, py); }, LONG_PRESS_MS);
    }
    // A widget that can raise a menu (dropdown): toggle it open.
    if (w && w.menuSpec) {
      openDropdownId = hit.id;
      render();
      return;
    }
    if (w && typeof w.value === 'function') {
      // Ranged control: set value to where you touched (down = jump-to), and arm
      // dragging so the thumb tracks the finger. preventDefault + pointer capture
      // keep the whole drag ours (no scroll-steal when it drifts vertically).
      ev.preventDefault();
      dragNode = hit;
      try { canvas.setPointerCapture(ev.pointerId); } catch {}
      dispatch(hit, EVENT.input, w.value(hit, px, py, renderCtx));
      return;
    }
    // A context-menu-only node (no press handler) waits for the long-press; don't
    // flash a press for it.
    if (w && w.contextMenu && !(hit.handlers && hit.handlers.size)) return;
    pressedId = hit.id; render();                       // immediate pressed-state flash
    dispatch(hit, EVENT.press);                         // wasm mutates + presents
    setTimeout(() => { pressedId = null; render(); }, 120);
  }, { passive: false });

  canvas.addEventListener('pointermove', (ev) => {
    // Scroll drag: translate the scene by the finger's vertical delta, tracking
    // velocity (last-frame px delta) so release can launch momentum.
    if (scrollDrag) {
      ev.preventDefault();
      const [, py] = localXY(ev);
      const dy = py - scrollDrag.startY;
      if (Math.abs(dy) > 4) scrollDrag.moved = true;
      const prev = scrollY;
      let target = scrollDrag.startScroll - dy;          // drag down -> content moves down
      // iOS rubber-band: past an edge, the content follows the finger with
      // resistance (only RUBBER of the overscroll distance) instead of 1:1.
      const max = maxBound();
      if (target < 0) target = target * RUBBER;
      else if (target > max) target = max + (target - max) * RUBBER;
      scrollY = target;
      scrollDrag.vel = scrollY - prev;                   // px since last move = velocity
      render();
      return;
    }
    // Cancel a pending long-press only if the finger moves beyond the slop radius
    // (a real hold always wobbles a few px; a true drag/scroll exceeds slop).
    if (longPressTimer && longPressXY) {
      const [sx, sy] = longPressXY;
      const [mx, my] = localXY(ev);
      if (Math.hypot(mx - sx, my - sy) > LONG_PRESS_SLOP) cancelLongPress();
    }
    if (!dragNode) return;
    ev.preventDefault();
    // Only the x drives the value; vertical drift (e.g. toward a label) is
    // ignored, so the drag holds anywhere on the canvas once captured.
    const [px, py] = localXY(ev);
    const w = widgetFor(dragNode.kind);
    dispatch(dragNode, EVENT.input, w.value(dragNode, px, py, renderCtx));
  }, { passive: false });

  const endDrag = (ev) => {
    cancelLongPress();                          // a lift before the hold elapsed = a tap, not long-press
    if (scrollDrag) {
      try { canvas.releasePointerCapture(ev.pointerId); } catch {}
      const v = scrollDrag.vel || 0;
      scrollDrag = null;
      // Flick -> glide (momentum also springs back if it hits an edge); otherwise
      // if we were left overscrolled, spring back to the boundary.
      if (Math.abs(v) > 1) startMomentum(v);
      else settleScroll();
      return;
    }
    if (!dragNode) return;
    try { canvas.releasePointerCapture(ev.pointerId); } catch {}
    dragNode = null;
  };
  canvas.addEventListener('pointerup', endDrag);
  canvas.addEventListener('pointercancel', endDrag);

  // Wheel / trackpad scroll (desktop) — clamps hard (no rubber-band for a wheel).
  canvas.addEventListener('wheel', (ev) => {
    if (maxBound() <= 0) return;
    ev.preventDefault();
    stopMomentum();
    scrollY = Math.max(0, Math.min(scrollY + ev.deltaY, maxBound()));
    render();
  }, { passive: false });

  // Right-click (desktop) -> the same context menu, anchored at the pointer.
  canvas.addEventListener('contextmenu', (ev) => {
    ev.preventDefault();                        // suppress the browser menu
    const [px, py] = localXY(ev);
    // Dismiss any open menu first; then raise the context menu (if any) here.
    openDropdownId = null; contextSpec = null; contextNode = null;
    if (!openContextMenu(px, py)) render();
  });

  // Hidden-input keystrokes drive the focused text field: the host owns the
  // value (so the field shows what's typed even if the handler ignores it), then
  // the handler gets an `input` event with the text. `blur` commits (`change`).
  const kbd = document.getElementById('kbd');
  if (kbd) {
    kbd.addEventListener('input', () => {
      if (focusedId === null) return;
      const node = nodes.get(focusedId);
      if (!node) return;
      (node._text ??= {})[TEXTKEY.value] = kbd.value;
      startBlink();                              // keep the caret solid while typing
      dispatchText(node, EVENT.input, kbd.value);
      render();
    });
    kbd.addEventListener('blur', () => { if (focusedId !== null) blurField(); });
  }
  // The soft keyboard shrinks the visual viewport; track that inset and keep the
  // focused field above it. (No-op on desktop, where visualViewport ~= layout.)
  if (window.visualViewport) {
      const onVV = () => {
      kbInset = viewportInset();
      // Lift the field only on the FIRST keyboard-open resize (latched); later
      // resizes (predictive bar, etc.) just update the inset + redraw, no jump.
      if (focusedId !== null && !kbScrolled && kbInset > 0) liftFocusedOnce();
      else render();
    };
    window.visualViewport.addEventListener('resize', onVV);
    window.visualViewport.addEventListener('scroll', onVV);
  }

  // Re-fit on a viewport change: rebuild the backing store, refresh viewportH so
  // maxBound() is computed against the NEW size (it would otherwise clamp scrollY
  // with the stale height from the last render), clamp scroll into the new range,
  // then redraw. stopMomentum so a glide in flight can't fling past the new edge.
  const refit = () => {
    resize();
    viewportH = canvas.clientHeight;
    stopMomentum();
    scrollY = Math.max(0, Math.min(scrollY, maxBound()));
    render();
  };
  // A ResizeObserver on the canvas is the RELIABLE signal: iPad Safari does not
  // dependably fire window 'resize' for Stage Manager / split-view / multitasking
  // size changes, but the observer fires whenever the element's box actually
  // changes — so the canvas, scroll bounds, and centering always track the window.
  if (typeof ResizeObserver !== 'undefined') new ResizeObserver(refit).observe(canvas);
  // Keep the window listeners too (older Safari, desktop) — refit is idempotent.
  window.addEventListener('resize', refit);
  window.addEventListener('orientationchange', () => { refit(); requestAnimationFrame(refit); });
}
main();
