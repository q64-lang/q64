// ---- the retained tree (generic, VALIDATED applier) --------------------------
// Scene owns the node tree + the five ops, schema-validating each before it
// touches the tree (spec §"Host obligations"). This host is one backend over it;
// the soft renderer is another. nodes/ROOT alias into the scene so the render +
// input code below reads unchanged.
const scene = new Scene({ onReject: (m) => log('drop: ' + m) });
const nodes = scene.nodes;
const ROOT = scene.ROOT;
// Evict glyph caches when the scene removes a node.
scene.onNodeRemoved = (id) => { glyphCache.delete(id); glyphKey.delete(id); };

let glyphCache = new Map();  // nodeId -> {tex,view,w,h}; rebuilt only when text changes
let glyphKey = new Map();    // nodeId -> last text string used, to skip rebuilds
let pressedId = null;
let focusedId = null;        // the text_input node id with keyboard focus, or null
let caretOn = true;          // caret blink phase (visible) while a field is focused
let blinkTimer = null;       // setInterval handle driving the blink
let kbScrolled = false;      // have we already lifted the focused field above the keyboard?
let instance;

// Host→app text scratch: when the user types, the host writes the field's UTF-8
// into wasm linear memory here and calls on_<id>(node, event, ptr, len) so the
// handler's `text: str` param points at it. A fixed high offset in the single
// 64 KB page — q64's static data + arena live low and never reach it for a UI
// handler (which doesn't allocate). Clamped to TEXT_CAP bytes.
const TEXT_BUF = 0xf000;
const TEXT_CAP = 0x800;

function textStringFor(node) {
  const id = node.attrs.get(ATTR.text_id);
  if (id === undefined) return null;
  const n = Number(id);
  // text_id >= CATALOG_BASE is a catalog string; below it is a literal integer
  // (e.g. a live counter), so 'show the number 0' never collides with CATALOG[0].
  return (n >= CATALOG_BASE && n - CATALOG_BASE < CATALOG.length) ? CATALOG[n - CATALOG_BASE] : String(n);
}
function glyphFor(node) {
  const str = textStringFor(node);
  if (str === null) return null;
  if (glyphKey.get(node.id) !== str) {           // surgical: only a changed text re-rasterizes
    glyphCache.set(node.id, sdfTexture(str));
    glyphKey.set(node.id, str);
  }
  return glyphCache.get(node.id);
}

// ---- the wasm import face: the validated Scene ops + a backend present() -----
// Scene.face wires create/set_attr/remove/on to the validated applier; present()
// is this backend's frame commit (render + drain the mutation log). A set_attr
// may change a node's text, so we evict its glyph key around the applier.
function ops() {
  const sceneFace = scene.face(() => {
    // present() = the tree just changed -> relayout (Phase 1) then render (Phase 2).
    layout();
    render();
    const m = scene.drainMuts();
    if (m.length) log('mutate: ' + m.join(', '));
  });
  return {
    env: { out: () => {} },
    qview: {
      ...sceneFace,
      set_attr: (id, attr, value) => { glyphKey.delete(Number(id)); sceneFace.set_attr(id, attr, value); },
      // A STRING op: the app passed (ptr, len) into wasm linear memory; read the
      // UTF-8 and stash it on the node under `key` (TEXTKEY: value | placeholder).
      // The text_input widget renders node._text; a changed string re-rasterizes
      // via the string-keyed glyph cache (no per-node invalidation needed).
      set_text: (id, key, ptr, len) => {
        const n = nodes.get(Number(id));
        if (!n) return;
        (n._text ??= {})[Number(key)] = readUtf8(ptr, len);
      },
    },
  };
}

// Decode a (ptr, len) span of the wasm instance's linear memory as UTF-8. Used
// by the string ops (set_text) and to read back validated/echoed text.
const decoder = new TextDecoder();
function readUtf8(ptr, len) {
  return decoder.decode(new Uint8Array(instance.exports.memory.buffer, Number(ptr), Number(len)));
}

// ATTR.surface role tag -> theme token key (the translucent material fills).
const SURFACE_KEY = { [SURFACE.none]: 'none', [SURFACE.surface]: 'surface', [SURFACE.material]: 'material', [SURFACE.materialThin]: 'materialThin', [SURFACE.scrim]: 'scrim' };

// ---- render: walk the retained tree, dispatch each node to its widget --------
// `layoutMap` (id -> {x,y,w,h}) holds resolved geometry from the arrange pass
// (stacks own their children's coords). When a node has a layout entry, r.attr
// returns its laid-out x/y/w/h transparently — widgets read geometry the same
// way whether they're absolute or inside an HStack/VStack.
let layoutMap = new Map();
const GEOM = { [ATTR.x]: 'x', [ATTR.y]: 'y', [ATTR.w]: 'w', [ATTR.h]: 'h' };
// Host-managed vertical scroll: the canvas stays viewport-sized; the whole scene
// is translated up by scrollY at draw time (and touches translated down to match),
// so content taller than the screen is reachable without native scroll fighting
// the slider/long-press gestures. The pinned top bar opts out (drawn unshifted).
let scrollY = 0, contentH = 0, viewportH = 0;
// Horizontal centering: when the viewport is wider than the content (iPad,
// landscape, desktop), shift everything right by offsetX so the UI sits centered
// instead of hugging the left. 0 on a phone where content == viewport width.
let offsetX = 0, contentW = 0;
const SCROLL_BOTTOM_PAD = 40;   // extra room past content so the last widget fully clears
// Soft-keyboard inset (CSS px): how much of the canvas the iOS/Android keyboard
// overlays while a text field is focused. Detected via visualViewport. It both
// extends the scroll range (so a bottom field can rise above the keyboard) and
// defines the visible region we scroll the focused field into.
let kbInset = 0;
// The true scroll limit. Includes kbInset so content can scroll up past the
// keyboard when one is open. Module-scoped so focus/keyboard logic can use it.
function maxBound() { return Math.max(0, contentH + SCROLL_BOTTOM_PAD + kbInset - viewportH); }
// Current keyboard inset from the visual viewport: the canvas area below the
// shrunken visible region. ~0 when no keyboard is up.
function viewportInset() {
  const vv = window.visualViewport;
  const cv = document.getElementById('gpu');
  if (!vv || !cv) return 0;
  const r = cv.getBoundingClientRect();
  return Math.max(0, r.top + cv.clientHeight - vv.height);
}
// Scroll the focused field above the keyboard (into the visible region). Called
// on focus and whenever the visual viewport changes (keyboard open/close).
function ensureFocusedVisible() {
  if (focusedId === null) return;
  const cv = document.getElementById('gpu');
  const rc = layoutMap.get(focusedId);
  if (!cv || !rc) return;
  kbInset = viewportInset();
  const visibleBottom = cv.clientHeight - kbInset;
  const fieldBottom = rc.y - scrollY + rc.h;     // field's on-screen bottom (canvas-local)
  const margin = 16;
  if (fieldBottom > visibleBottom - margin) {
    scrollY = Math.max(0, Math.min(scrollY + fieldBottom - (visibleBottom - margin), maxBound()));
  }
  render();
}
const renderCtx = {
  pass: null, drawPrim, sdfText: sdfTexture, theme: THEME, platform: PLATFORM,
  attr: (node, a, dflt) => {
    const g = GEOM[a]; const lay = g && layoutMap.get(node.id);
    let v = lay ? lay[g] : node.attrs.get(a);
    v = v === undefined ? dflt : Number(v);
    if (a === ATTR.y && !node._pinned) v -= scrollY;     // translate scene up
    if (a === ATTR.x) v += offsetX;                       // center horizontally
    return v;
  },
  color: (node, a, dflt) => { const v = node.attrs.get(a); return v === undefined ? dflt : unpackColor(v); },
  // Resolve a node's fill, honoring a semantic ATTR.surface role (theme-resolved
  // translucent material) over a literal ATTR.fill over the given default.
  surfaceFill: (node, dflt) => {
    const role = node.attrs.get(ATTR.surface);
    if (role !== undefined) {
      const key = SURFACE_KEY[Number(role)];
      if (key && key !== 'none') return THEME[key] ?? dflt;
      if (key === 'none') return null;
    }
    const lit = node.attrs.get(ATTR.fill);
    return lit === undefined ? dflt : unpackColor(lit);
  },
  textFor: (node) => glyphFor(node),
  glyphForId: (textId) => glyphForCatalog(textId),
  isPressed: (id) => id === pressedId,
  isOpen: (id) => id === openDropdownId,
  // --- text_input helpers (host owns the editable value) ---
  // The field's current value / placeholder strings (set via the set_text op).
  textValue: (node) => node._text?.[TEXTKEY.value] ?? '',
  textPlaceholder: (node) => node._text?.[TEXTKEY.placeholder] ?? '',
  isFocused: (id) => id === focusedId,
  caretVisible: () => caretOn,
  // An SDF for an arbitrary string, cached by (string + size) — for field text
  // that changes per keystroke (no per-node glyph slot).
  glyphForStr: (str, sizePx) => glyphForStr(str, sizePx),
};

// The LAYOUT context: a PURE view for the layout pass. Its attr reads raw node
// attrs (no layoutMap, no scroll) — layout is computing those rects, and must be
// independent of scroll/render state (SwiftUI keeps layout pure). Shares text
// measurement so a label/button can size to its glyph.
const layoutCtx = {
  theme: THEME, platform: PLATFORM,
  attr: (node, a, dflt) => { const v = node.attrs.get(a); return v === undefined ? dflt : Number(v); },
  textFor: (node) => glyphFor(node),
  glyphForId: (textId) => glyphForCatalog(textId),
};

// The node currently showing a menu (one open at a time), or null. Any widget
// exposing menuSpec(node, r) can raise the shared popup; today that's the
// dropdown, tomorrow a context menu.
let openDropdownId = null;
// A context menu (long-press / right-click) raised at a point: its popup spec +
// the node it belongs to. Separate from openDropdownId (anchored differently).
let contextSpec = null, contextNode = null;

// The menu spec for the currently-open node (or null) — built fresh each use so
// it reflects current selection/geometry. The host injects the viewport (CSS px)
// so the popup can flip/clamp to stay on-screen.
function openMenuSpec() {
  if (openDropdownId === null) return null;
  const n = nodes.get(openDropdownId);
  const w = n && widgetFor(n.kind);
  if (!w || !w.menuSpec) return null;
  return withViewport(w.menuSpec(n, renderCtx));
}

// Inject the viewport (CSS px) into a popup spec so it can flip/clamp on-screen.
function withViewport(spec) {
  if (spec) {
    const cv = document.getElementById('gpu');
    if (cv) spec.viewport = { w: cv.clientWidth, h: cv.clientHeight };
  }
  return spec;
}

// A glyph for a host-catalog id directly (popup option rows), cached.
const idGlyphCache = new Map();
function glyphForCatalog(textId) {
  const n = Number(textId);
  const str = (n >= CATALOG_BASE && n - CATALOG_BASE < CATALOG.length) ? CATALOG[n - CATALOG_BASE] : String(n);
  if (!idGlyphCache.has(str)) idGlyphCache.set(str, sdfTexture(str));
  return idGlyphCache.get(str);
}

// An SDF for an arbitrary string at a size, cached by "size:str". For text_input
// values, which change per keystroke and have no per-node glyph slot. Empty
// string → null (nothing to draw). Cache is unbounded but a UI types few strings.
const strGlyphCache = new Map();
function glyphForStr(str, sizePx = 17) {
  if (!str) return null;
  const key = `${sizePx}:${str}`;
  if (!strGlyphCache.has(key)) strGlyphCache.set(key, sdfTexture(str, sizePx));
  return strGlyphCache.get(key);
}

// ===========================================================================
// Phase 1 — LAYOUT (one pure pass, SwiftUI-style). Geometry only: measure +
// arrange the tree into resolved rects (layoutMap). No scroll, no GPU, no clip.
// Recomputed only when the tree changes (layout()), NOT every frame. Also derives
// the content height and the sticky-header band from the pure geometry.
// ===========================================================================
let headerH = 0;            // bottom of the pinned header band (layout space)
function layout() {
  layoutMap = computeLayout(scene, layoutCtx);
  contentH = 0; headerH = 0; contentW = 0;
  for (const [id, rc] of layoutMap) {
    contentH = Math.max(contentH, rc.y + rc.h);
    contentW = Math.max(contentW, rc.x + rc.w);
    const n = nodes.get(id);
    if (n && n._pinned) headerH = Math.max(headerH, rc.y + rc.h);
  }
}

// ===========================================================================
// Phase 2 — RENDER PATH (consumes the resolved geometry). Applies scroll as a
// draw-time translate, clips scrollable content below the sticky header, draws.
// The GPU host and the soft renderer are two such paths over the same layout.
// ===========================================================================
function render() {
  const cv = document.getElementById('gpu');
  viewportH = cv ? cv.clientHeight : 0;
  const viewportW = cv ? cv.clientWidth : 0;
  // Center the content block when the viewport is wider than it (iPad/desktop);
  // the layout was built left-anchored (x from 0), so this shifts the whole UI.
  offsetX = Math.max(0, Math.round((viewportW - contentW) / 2));
  // NB: scrollY is NOT hard-clamped here — it may sit slightly past the edges
  // during an iOS-style rubber-band overscroll; the drag applies resistance and
  // release springs it back (see settleScroll). maxBound() is the true limit.

  const frame = beginFrame(THEME.bg);
  renderCtx.pass = frame.pass;
  // Pass 1: scrollable (unpinned) content, clipped below the header band.
  if (headerH > 0) setScissor(frame.pass, { x: 0, y: headerH, w: 10000, h: Math.max(0, viewportH - headerH) });
  walk(ROOT, false);
  // Pass 2: pinned chrome (the sticky header), unclipped, on top.
  setScissor(frame.pass, null);
  if (headerH > 0) walk(ROOT, true);
  // Overlays last, on top of everything: the open menu or context menu (shared
  // popup primitive). Both get the viewport so they flip/clamp near edges.
  const spec = contextSpec ? withViewport(contextSpec) : openMenuSpec();
  if (spec) drawMenu(spec, renderCtx);
  endFrame(frame);
}
// walk with a `pinned` filter: false = draw only unpinned subtrees; true = only
// pinned nodes. A node's pinned-ness is inherited from its nearest pinned ancestor.
function walk(id, wantPinned, pinned = false) {
  const n = nodes.get(id); if (!n) return;
  const isPinned = pinned || !!n._pinned;
  if (id !== ROOT && isPinned === wantPinned) {
    const w = widgetFor(n.kind);
    if (w && w.draw) w.draw(n, renderCtx);
  }
  for (const c of n.children) walk(c, wantPinned, isPinned);
}

// ---- input: hit-test the tree, fire the wired handler via on_event -----------
function hitTest(px, py) {
  // Topmost-first: later children draw over earlier; walk in reverse.
  let found = null;
  const visit = (id) => {
    const n = nodes.get(id); if (!n) return;
    for (let i = n.children.length - 1; i >= 0; i--) visit(n.children[i]);
    if (found) return;
    if (id !== ROOT) {
      const w = widgetFor(n.kind);
      if (w && w.hit && w.hit(n, px, py, renderCtx)) found = n;
    }
  };
  visit(ROOT);
  return found;
}

function dispatch(node, event, payload = 0) {
  // Find the handler for this event; if the node has no handler for this exact
  // event (e.g. a slider wired to `press` but we're sending `input` during a
  // drag), fall back to its single registered handler. A Stage-1 control wires
  // exactly one handler, so this routes drag/input to it without the producer
  // having to wire every event id.
  let handler = node.handlers.get(event);
  if (handler === undefined) {
    if (node.handlers.size === 1) handler = node.handlers.values().next().value;
    else return;
  }
  // Stage-1 dispatch (spec/qview-protocol.md §Events). The wasm handler reads
  // state, mutates the exact node(s), and calls present(). Two shapes, in order:
  //   1. per-handler export `on_<id>` (the handler id from qview.on) — branchless,
  //      one export per wired control; what the compiler emits cleanly today.
  //   2. single dispatcher `on_event(node, event)` — fallback when no on_<id>.
  // All take (node, event, payload) i64 args: `payload` is a widget-computed
  // value (e.g. a slider's value from the touch position) — the event-payload
  // shape from the spec. Handlers that ignore it just take fewer params.
  const perHandler = instance.exports[`on_${handler}`];
  const fn = typeof perHandler === 'function' ? perHandler : instance.exports.on_event;
  if (typeof fn === 'function') fn(BigInt(node.id), BigInt(event), BigInt(Math.trunc(payload)));
  else log(`wasm exports no on_${handler} or on_event`);
}

// Dispatch a text event to a node's handler, passing the string as a `str` param:
// write the UTF-8 into the wasm text buffer and call on_<id>(node, event, ptr,
// len). The handler reads/validates it (text.len, ==, slice, …) and mutates the
// tree + present()s. Only the per-handler `on_<id>` shape carries a str param.
function dispatchText(node, event, str) {
  let handler = node.handlers.get(event);
  if (handler === undefined) {
    if (node.handlers.size === 1) handler = node.handlers.values().next().value;
    else return;
  }
  const fn = instance.exports[`on_${handler}`];
  if (typeof fn !== 'function') return;
  const bytes = new TextEncoder().encode(str);
  const n = Math.min(bytes.length, TEXT_CAP);
  new Uint8Array(instance.exports.memory.buffer, TEXT_BUF, TEXT_CAP).set(bytes.subarray(0, n));
  // node/event are i64 (BigInt); ptr/len are i32 address-width params (Number).
  fn(BigInt(node.id), BigInt(event), TEXT_BUF, n);
}

// Give a text field keyboard focus: position the hidden <input> over it (so iOS
// keeps it on-screen + scrolls to it), seed its value, and focus() — which must
// run inside the tap gesture to raise the soft keyboard. We draw the text/caret;
// the input only captures keystrokes.
// Start/refresh the caret blink (visible now, then toggle ~every 530ms). Called
// on focus and reset on each keystroke so the caret stays solid while typing.
function startBlink() {
  caretOn = true;
  if (blinkTimer) clearInterval(blinkTimer);
  blinkTimer = setInterval(() => { caretOn = !caretOn; if (focusedId !== null) render(); }, 530);
}
function stopBlink() { if (blinkTimer) clearInterval(blinkTimer); blinkTimer = null; caretOn = true; }

// Lift the focused field above the keyboard exactly ONCE per focus session.
// iOS fires extra visualViewport resizes (e.g. the predictive bar appears on the
// first keystroke) that would otherwise re-scroll and make the field jump again;
// the latch keeps the lift to the single keyboard-open event.
function liftFocusedOnce() {
  if (focusedId === null || kbScrolled) return;
  kbInset = viewportInset();
  if (kbInset <= 0) return;                      // keyboard not up yet — wait for the resize
  ensureFocusedVisible();
  kbScrolled = true;
}

function focusField(node) {
  focusedId = node.id;
  kbScrolled = false;
  startBlink();
  const kbd = document.getElementById('kbd');
  const cv = document.getElementById('gpu');
  const rc = layoutMap.get(node.id);
  if (kbd && cv && rc) {
    const r = cv.getBoundingClientRect();
    kbd.style.left = `${r.left + offsetX + rc.x}px`;
    kbd.style.top = `${r.top + rc.y - scrollY}px`;
    kbd.style.width = `${rc.w}px`;
    kbd.style.height = `${rc.h}px`;
    kbd.value = renderCtx.textValue(node);
    kbd.focus();
    try { kbd.setSelectionRange(kbd.value.length, kbd.value.length); } catch {}
  }
  render();
  // The keyboard animates in over a few hundred ms; the visualViewport 'resize'
  // (keyboard appearing) lifts the field and latches it. This timeout is a
  // fallback if that event doesn't fire; both go through liftFocusedOnce so the
  // field is lifted exactly once (no second jump on the first keystroke).
  setTimeout(liftFocusedOnce, 350);
}

// Drop keyboard focus and commit (a `change` event to the handler).
function blurField() {
  if (focusedId === null) return;
  const node = nodes.get(focusedId);
  focusedId = null;
  kbScrolled = false;
  stopBlink();
  kbInset = 0;                                   // keyboard is closing; reclaim the room
  const kbd = document.getElementById('kbd');
  if (kbd) kbd.blur();
  scrollY = Math.max(0, Math.min(scrollY, maxBound()));
  if (node) dispatchText(node, EVENT.change, renderCtx.textValue(node));
  render();
}

